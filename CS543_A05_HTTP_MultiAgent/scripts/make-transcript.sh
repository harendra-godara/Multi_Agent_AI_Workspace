#!/usr/bin/env bash
# Generates curl-transcript.txt: starts the service (port 3000, plus a tiny-limit copy on 3001), runs curl -v, stops them.
cd "$(dirname "$0")/.."
OUT=curl-transcript.txt
PORT=3000 node server.js >/dev/null 2>&1 & P1=$!
RATE_LIMIT_MAX=3 PORT=3001 node server.js >/dev/null 2>&1 & P2=$!
trap 'kill $P1 $P2 2>/dev/null' EXIT
sleep 1.5

step() { echo; echo "### $1"; echo "\$ $2"; eval "$2" 2>&1 | grep -v '^\*' | tr -d '\r'; }

{
echo "CS543 A05 - curl -v transcript (Tasks service, Multi-Agent AI Workspace)"
echo "Generated by scripts/make-transcript.sh"

step "D1a. CREATE -> 201 + Location" \
 "curl -sv -X POST http://localhost:3000/tasks -H 'Authorization: Bearer demo-token' -H 'Content-Type: application/json' -H 'Idempotency-Key: demo-key-1' -d '{\"title\":\"Write release notes\",\"workspaceId\":\"ws-1\",\"steps\":[{\"agent\":\"Docs Agent\",\"attempts\":1}]}'"

step "D1b. SAME CREATE, SAME Idempotency-Key -> the original (id 4 again, no duplicate)" \
 "curl -sv -X POST http://localhost:3000/tasks -H 'Authorization: Bearer demo-token' -H 'Content-Type: application/json' -H 'Idempotency-Key: demo-key-1' -d '{\"title\":\"Write release notes\",\"workspaceId\":\"ws-1\",\"steps\":[{\"agent\":\"Docs Agent\",\"attempts\":1}]}'"

step "Proof: still only one 'Write release notes' task" \
 "curl -s 'http://localhost:3000/tasks?limit=100' | grep -o 'Write release notes' | wc -l"

step "B4. GET one task -> 200 + ETag + Cache-Control" \
 "curl -sv http://localhost:3000/tasks/1"
ETAG=$(curl -sI http://localhost:3000/tasks/1 | awk -F': ' 'tolower($1)=="etag"{print $2}' | tr -d '\r')
echo; echo "# ETAG captured from the response above: $ETAG"

step "D1c. CONDITIONAL GET with If-None-Match -> 304 Not Modified (no body)" \
 "curl -sv http://localhost:3000/tasks/1 -H 'If-None-Match: $ETAG'"

step "D1d. CONDITIONAL WRITE with a stale If-Match -> 412 Precondition Failed" \
 "curl -sv -X PATCH http://localhost:3000/tasks/1 -H 'Authorization: Bearer demo-token' -H 'Content-Type: application/json' -H 'If-Match: \"stale-etag\"' -d '{\"title\":\"Overwrite attempt\"}'"

step "C2. CONDITIONAL WRITE with the fresh If-Match -> 200 and a NEW ETag" \
 "curl -sv -X PATCH http://localhost:3000/tasks/1 -H 'Authorization: Bearer demo-token' -H 'Content-Type: application/json' -H 'If-Match: $ETAG' -d '{\"title\":\"Summarise project requirements (v2)\"}'"

step "D1e. 400 Bad Request - malformed JSON" \
 "curl -sv -X POST http://localhost:3000/tasks -H 'Authorization: Bearer demo-token' -H 'Content-Type: application/json' -d '{\"title\": '"

step "Contrast: 422 Unprocessable - valid JSON, domain refusal (empty steps)" \
 "curl -sv -X POST http://localhost:3000/tasks -H 'Authorization: Bearer demo-token' -H 'Content-Type: application/json' -d '{\"title\":\"x\",\"workspaceId\":\"ws-1\",\"steps\":[]}'"

step "D1f. 404 Not Found" \
 "curl -sv http://localhost:3000/tasks/999"

step "D1g. 401 Unauthorized - no token on a write" \
 "curl -sv -X POST http://localhost:3000/tasks -H 'Content-Type: application/json' -d '{\"title\":\"x\"}'"

step "B1. 406 Not Acceptable - client demands XML" \
 "curl -sv http://localhost:3000/tasks/1 -H 'Accept: application/xml'"

step "A5. OPTIONS -> Allow header" \
 "curl -sv -X OPTIONS http://localhost:3000/tasks/1"

step "B6. CORS preflight from another origin" \
 "curl -sv -X OPTIONS http://localhost:3000/tasks -H 'Origin: http://localhost:5173' -H 'Access-Control-Request-Method: POST' -H 'Access-Control-Request-Headers: authorization,content-type'"

step "A5. X-HTTP-Method-Override: a POST that acts as DELETE (task 3 is completed, so it can be removed)" \
 "curl -sv -X POST http://localhost:3000/tasks/3 -H 'Authorization: Bearer demo-token' -H 'X-HTTP-Method-Override: DELETE'"

step "A2. Non-CRUD action as a sub-resource: POST /tasks/1/start -> 200" \
 "curl -sv -X POST http://localhost:3000/tasks/1/start -H 'Authorization: Bearer demo-token'"

step "A2. Illegal repeat: POST /tasks/1/start again -> 409" \
 "curl -sv -X POST http://localhost:3000/tasks/1/start -H 'Authorization: Bearer demo-token'"

step "B1. gzip on a larger JSON body" \
 "curl -sv -H 'Accept-Encoding: gzip' -o /dev/null http://localhost:3000/tasks"

step "B5. RATE LIMIT (server started with RATE_LIMIT_MAX=3): 4th request from one client -> 429 + Retry-After" \
 "for i in 1 2 3 4; do curl -s -o /dev/null -D - -H 'X-Client-Id: burst' http://localhost:3001/tasks/1 | grep -iE '^(HTTP|x-ratelimit|retry-after)'; echo ---; done"
} > "$OUT"
echo "wrote $OUT ($(wc -l < $OUT) lines)"
