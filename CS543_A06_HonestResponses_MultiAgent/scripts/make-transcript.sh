#!/usr/bin/env bash
# Generates transcript.txt with curl -i: starts the service on 3000, a tiny-limit copy on 3001 and a maintenance copy on 3002.
cd "$(dirname "$0")/.."
OUT=transcript.txt
PORT=3000 node server.js >/dev/null 2>/tmp/a06-server.log & P1=$!
RATE_LIMIT_MAX=3 PORT=3001 node server.js >/dev/null 2>&1 & P2=$!
MAINTENANCE=1 PORT=3002 node server.js >/dev/null 2>&1 & P3=$!
trap 'kill $P1 $P2 $P3 2>/dev/null' EXIT
sleep 1.5

H='-H "Authorization: Bearer demo-token" -H "Content-Type: application/json"'
step() { echo; echo "### $1"; echo "\$ $2"; eval "$2" 2>&1 | tr -d '\r'; }

{
echo "CS543 A06 - curl transcript (Tasks service, Multi-Agent AI Workspace)"
echo "Generated by scripts/make-transcript.sh   (curl -i: status line + headers + body)"
echo "Mapping used in this project:  order -> task,  items/qty -> steps/attempts,  address -> workspaceId"

echo; echo "############ D1. SUCCESS TRANSCRIPT ############"
step "D1. Happy path: POST /tasks -> 201 + Location + JSON body" \
 "curl -si -X POST http://localhost:3000/tasks -H 'Authorization: Bearer demo-token' -H 'Content-Type: application/json' -H 'Idempotency-Key: demo-key-1' -d '{\"title\":\"Write release notes\",\"workspaceId\":\"ws-1\",\"steps\":[{\"agent\":\"Docs Agent\",\"attempts\":1}]}'"

echo; echo "############ D2. FAILURE TRANSCRIPT (each status + Problem Details body) ############"
step "D2a. Empty cart -> empty-steps (422)" \
 "curl -si -X POST http://localhost:3000/tasks -H 'Authorization: Bearer demo-token' -H 'Content-Type: application/json' -d '{\"title\":\"No steps\",\"workspaceId\":\"ws-1\",\"steps\":[]}'"

step "D2b. qty <= 0 AND a missing field, reported together -> validation-error (422) with errors[]" \
 "curl -si -X POST http://localhost:3000/tasks -H 'Authorization: Bearer demo-token' -H 'Content-Type: application/json' -d '{\"workspaceId\":\"ws-1\",\"steps\":[{\"agent\":\"Code Agent\",\"attempts\":0}]}'"

step "D2c. Unknown id -> task-not-found (404)" \
 "curl -si http://localhost:3000/tasks/999"

step "D2d. Illegal transition: complete a task that is still pending -> illegal-transition (409)" \
 "curl -si -X POST http://localhost:3000/tasks/1/complete -H 'Authorization: Bearer demo-token'"

step "D2e. Offline agent -> agent-unavailable (422)" \
 "curl -si -X POST http://localhost:3000/tasks -H 'Authorization: Bearer demo-token' -H 'Content-Type: application/json' -d '{\"title\":\"Ship it\",\"workspaceId\":\"ws-1\",\"steps\":[{\"agent\":\"Deploy Agent\",\"attempts\":1}]}'"

curl -s -X POST http://localhost:3000/tasks -H 'Authorization: Bearer demo-token' -H 'Content-Type: application/json' -d '{"title":"Quota test","workspaceId":"ws-exhausted","steps":[{"agent":"Code Agent","attempts":1}]}' >/dev/null
step "D2f. Workspace out of quota (task 5 was created in ws-exhausted) -> execution-declined (422)" \
 "curl -si -X POST http://localhost:3000/tasks/5/start -H 'Authorization: Bearer demo-token'"

curl -s -X POST http://localhost:3000/tasks -H 'Authorization: Bearer demo-token' -H 'Content-Type: application/json' -d '{"title":"Crash test","workspaceId":"ws-crash","steps":[{"agent":"Code Agent","attempts":1}]}' >/dev/null
step "D2g. Internal failure (task 6, ws-crash) -> clean 500, no stack trace / DB message (B4)" \
 "curl -si -X POST http://localhost:3000/tasks/6/start -H 'Authorization: Bearer demo-token'"

step "D2h. Malformed JSON -> malformed-json (400)" \
 "curl -si -X POST http://localhost:3000/tasks -H 'Authorization: Bearer demo-token' -H 'Content-Type: application/json' -d '{\"title\": '"

step "D2i. No token -> unauthorized (401)" \
 "curl -si -X POST http://localhost:3000/tasks -H 'Content-Type: application/json' -d '{\"title\":\"x\"}'"

step "D2j. Stale If-Match -> precondition-failed (412)" \
 "curl -si -X PATCH http://localhost:3000/tasks/1 -H 'Authorization: Bearer demo-token' -H 'Content-Type: application/json' -H 'If-Match: \"stale-etag\"' -d '{\"title\":\"Overwrite attempt\"}'"

step "D2k. Cannot produce what the client demands (Accept: text/html) -> not-acceptable (406)" \
 "curl -si http://localhost:3000/tasks/1 -H 'Accept: text/html'"

echo; echo "--- D2l. RATE LIMIT (a copy of the service on port 3001 with RATE_LIMIT_MAX=3): 3 requests are fine, the 4th gets 429 + Retry-After ---"
for i in 1 2 3; do curl -s -o /dev/null -H 'X-Client-Id: burst' http://localhost:3001/tasks/1; done
step "D2l. 4th request from the same client -> rate-limited (429) with Retry-After" \
 "curl -si -H 'X-Client-Id: burst' http://localhost:3001/tasks/1"

step "D2m. Maintenance mode (a copy on port 3002 with MAINTENANCE=1) -> service-unavailable (503) with Retry-After" \
 "curl -si -X POST http://localhost:3002/tasks -H 'Authorization: Bearer demo-token' -H 'Content-Type: application/json' -d '{\"title\":\"x\",\"workspaceId\":\"ws-1\",\"steps\":[{\"agent\":\"Code Agent\",\"attempts\":1}]}'"

echo; echo "############ D3. NEGOTIATION CHECK ############"
step "D3a. Same task as JSON (Accept: application/json)" \
 "curl -si http://localhost:3000/tasks/1 -H 'Accept: application/json'"
step "D3b. Same task as XML (Accept: application/xml)" \
 "curl -si http://localhost:3000/tasks/1 -H 'Accept: application/xml'"

echo; echo "############ D4. NO REGRESSIONS (A05 checks) ############"
step "D4a. Idempotent repeat: same Idempotency-Key + same body -> the original 201 (task 4, Idempotent-Replayed: true)" \
 "curl -si -X POST http://localhost:3000/tasks -H 'Authorization: Bearer demo-token' -H 'Content-Type: application/json' -H 'Idempotency-Key: demo-key-1' -d '{\"title\":\"Write release notes\",\"workspaceId\":\"ws-1\",\"steps\":[{\"agent\":\"Docs Agent\",\"attempts\":1}]}'"
ETAG=$(curl -sI http://localhost:3000/tasks/1 | awk -F': ' 'tolower($1)=="etag"{print $2}' | tr -d '\r')
step "D4b. Conditional GET -> 304 (ETag $ETAG)" \
 "curl -si http://localhost:3000/tasks/1 -H 'If-None-Match: $ETAG'"
step "D4c. Same Idempotency-Key, DIFFERENT body -> idempotency-key-reuse (422)" \
 "curl -si -X POST http://localhost:3000/tasks -H 'Authorization: Bearer demo-token' -H 'Content-Type: application/json' -H 'Idempotency-Key: demo-key-1' -d '{\"title\":\"A different task\",\"workspaceId\":\"ws-1\",\"steps\":[{\"agent\":\"Docs Agent\",\"attempts\":1}]}'"
echo; echo "--- Server-side log for the 500 above (this is where the detail went; the client never saw it) ---"
grep -E 'failed to start task' /tmp/a06-server.log | head -1 | cut -c1-200
} > "$OUT"
echo "wrote $OUT ($(wc -l < $OUT) lines)"
